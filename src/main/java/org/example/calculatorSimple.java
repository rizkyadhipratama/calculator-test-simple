package org.example;

public class calculatorSimple {
    public int sum(int a, int b){
        return a+b;
    }
    public int minus(int a, int b){
        return a-b;
    }
    public int times(int a, int b){
        return a*b;
    }
    public long divide(long a, long b){
        return a/b;
    }
}
